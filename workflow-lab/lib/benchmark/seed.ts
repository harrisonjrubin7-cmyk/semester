import { BENCHMARK_WORKFLOWS, SUITE_NAME, TEMPLATE_SUITE_ID } from "./benchmark.config";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

/** SQL for supabase/seed.sql: one template suite containing all 12 canonical workflows. Idempotent. */
export function renderSeedSql(): string {
  const rows = BENCHMARK_WORKFLOWS.map(
    (w) =>
      `  (${q(TEMPLATE_SUITE_ID)}, ${w.number}, ${q(w.slug)}, ${q(w.title)}, ${q(w.category)}, ${q(w.prompt)},\n` +
      `   ${j(w.requirements)},\n   ${j(w.capabilities)},\n   ${j(w.acceptanceCriteria)},\n` +
      `   ${q(w.recommendedPlatform)}, ${j(w.weights)}, ${w.requiresPersistence})`,
  ).join(",\n");

  return `-- GENERATED by scripts/generate-seed.ts from lib/benchmark/benchmark.config.ts. Do not edit by hand.
-- Seeds the canonical 12-workflow template suite. Safe to run repeatedly.
-- Run as the database owner (supabase db reset does; in the SQL editor you are postgres).
-- Users get their own editable copy through the clone_benchmark_template() RPC.

insert into public.benchmark_suites (id, name, description, owner_id, organization_id, is_template)
values (${q(TEMPLATE_SUITE_ID)}, ${q(SUITE_NAME)},
  'Canonical benchmark: the same 12 workflow prompts run on Claude Artifacts, ChatGPT Canvas and v0.', null, null, true)
on conflict (id) do update set name = excluded.name, description = excluded.description;

insert into public.benchmark_tasks
  (suite_id, task_number, slug, title, category, prompt, requirements, capabilities,
   acceptance_criteria, recommended_platform, rubric_weights, requires_persistence)
values
${rows}
on conflict (suite_id, task_number) do update set
  slug = excluded.slug, title = excluded.title, category = excluded.category, prompt = excluded.prompt,
  requirements = excluded.requirements, capabilities = excluded.capabilities,
  acceptance_criteria = excluded.acceptance_criteria, recommended_platform = excluded.recommended_platform,
  rubric_weights = excluded.rubric_weights, requires_persistence = excluded.requires_persistence;
`;
}
