// Regenerates src/lib/guardManifest.ts from every migration string under apps/*/src. Run from the workspace root:
//   node apps/semester-company-os/scripts/genGuardManifest.mjs
// tests/guardManifest.test.ts fails when this file is stale.
import fs from 'fs';
import path from 'path';

const root = 'apps';
const files = [];
const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) {
  if (e.name === 'node_modules' || e.name.startsWith('.')) continue;
  const p = path.join(d, e.name);
  if (e.isDirectory()) walk(p); else if (/\.tsx?$/.test(e.name) && p.includes(`${path.sep}src${path.sep}`) && !p.endsWith('guardManifest.ts')) files.push(p);
} };
for (const a of fs.readdirSync(root)) if (fs.existsSync(path.join(root, a, 'src'))) walk(path.join(root, a, 'src'));
const sources = files.sort().map((f) => fs.readFileSync(f, 'utf8'));
const tables = new Set(); const guards = new Map();
for (const src of sources) {
  for (const m of src.matchAll(/CREATE TABLE IF NOT EXISTS ([a-z_][a-z0-9_]*)/g)) tables.add(m[1]);
  for (const m of src.matchAll(/CREATE TRIGGER ([a-z_][a-z0-9_]*)\s+(BEFORE|AFTER)\s+([A-Z ]+?)\s+ON\s+([a-z_][a-z0-9_]*)/g))
    guards.set(`${m[4]}.${m[1]}`, { trigger: m[1], timing: m[2], events: m[3].trim(), table: m[4] });
}
const out = {
  tables: [...tables].sort(),
  guards: [...guards.values()].sort((a, b) => (a.table + a.trigger).localeCompare(b.table + b.trigger)),
};
const body = `// GENERATED by scripts/genGuardManifest.mjs from the migration strings in apps/*/src. Do not edit by hand.\n` +
  `import type { Manifest } from './schemaScan';\nexport const GUARD_MANIFEST: Manifest = ${JSON.stringify(out, null, 1)};\n`;
fs.writeFileSync('apps/semester-company-os/src/lib/guardManifest.ts', body);
console.log(`tables ${out.tables.length}, triggers ${out.guards.length}`);
