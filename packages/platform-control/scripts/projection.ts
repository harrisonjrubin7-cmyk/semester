import type { CapabilityRecord, RegistrySnapshot } from '../types.ts';

/**
 * The file registry projected into `private.registry_*`
 * (`supabase/migrations/20261011120000_platform_registry.sql`).
 *
 * The files are the authority; the tables are a read model for anything that
 * runs inside the database. So this renders idempotent upserts from the
 * registry rather than letting the tables be edited by hand, and the status
 * it writes is derived from capability maturity, never typed. The gate
 * triggers in the migration then refuse any status the chain does not support,
 * which is the point: a projection cannot claim more than its evidence.
 *
 * The output is a service-role script. Nothing applies it automatically.
 */

const literal = (value: string | null): string => value === null ? 'null' : `'${value.replace(/'/g, "''")}'`;
const statusLiteral = (value: string): string => `${literal(value)}::private.registry_status`;

const RISK_TIER: Record<CapabilityRecord['risk'], number> = { low: 0, medium: 1, high: 2, critical: 3 };

/** Maturity → registry status. Deployed needs production-ready evidence; tested needs e2e; implemented needs an api or a user interface. */
export function projectedStatus(maturity: CapabilityRecord['maturity']): 'draft' | 'implemented' | 'tested' | 'deployed' {
  if (maturity.production_ready) return 'deployed';
  if (maturity.e2e_tested) return 'tested';
  if (maturity.api || maturity.user_interface) return 'implemented';
  return 'draft';
}

export function renderRegistryProjection(snapshot: RegistrySnapshot): string {
  const inception = snapshot.inception!;
  const scopes = new Map((snapshot.workspaces ?? []).map((w) => [w.key, w]));
  const RANK: Record<ReturnType<typeof projectedStatus>, number> = { draft: 1, implemented: 2, tested: 3, deployed: 4 };
  // The gate requires a workspace to rank at least as high as each capability it holds, so it is projected at the highest of them.
  const workspaceRank = (key: string): number => Math.max(1, ...snapshot.capabilities.filter((c) => c.workspace === key).map((c) => RANK[projectedStatus(c.maturity)]));
  const WORKSPACE_STATUS = ['draft', 'implemented', 'tested', 'deployed'] as const;
  const operatingSystems = [...inception.operating_systems].sort((a, b) => a.key.localeCompare(b.key));
  const capabilities = [...snapshot.capabilities].sort((a, b) => a.key.localeCompare(b.key));
  const lines: string[] = [
    '-- Generated by packages/platform-control/scripts/build-atlas.ts from the registry files.',
    '-- Service-role only: upserts the file registry into private.registry_* (20261011120000_platform_registry.sql).',
    '-- Idempotent. Status is derived from maturity; the gate triggers refuse anything the evidence chain does not support.',
    '-- The gates read each other, so the passes run in an order that keeps every intermediate state legal:',
    '--   1. lower capabilities that come down, before their workspace is lowered beneath them;',
    '--   2. upsert workspaces;',
    '--   3. upsert capability rows as draft, so their evidence can exist before a status needs it;',
    '--   4. attach dependencies and evidence;',
    '--   5. raise capabilities to their projected status.',
    'begin;',
  ];
  lines.push('-- 1. Lower capabilities the projection takes below their current status.');
  for (const capability of capabilities) {
    const status = projectedStatus(capability.maturity);
    lines.push(`update private.registry_capabilities set status = ${statusLiteral(status)} where capability_key = ${literal(capability.key)} and private.registry_status_rank(status) > private.registry_status_rank(${statusLiteral(status)});`);
  }
  lines.push('-- 2. Workspaces.');
  for (const os of operatingSystems) {
    const classification = scopes.get(os.pilot_scopes[0])?.data_classification ?? 'internal';
    const status = os.status === 'blocked' ? 'blocked' : WORKSPACE_STATUS[workspaceRank(os.key) - 1];
    lines.push(
      `insert into private.registry_workspaces (workspace_key, name, os_family, base_route, owner_team, data_classification, status)`,
      `  values (${literal(os.key)}, ${literal(os.name)}, ${literal(os.os_family)}, ${literal(os.routes[0])}, ${literal(os.owner)}, ${literal(classification)}, ${statusLiteral(status)})`,
      `  on conflict (workspace_key) do update set name = excluded.name, os_family = excluded.os_family, base_route = excluded.base_route, owner_team = excluded.owner_team, data_classification = excluded.data_classification, status = excluded.status;`,
    );
  }
  lines.push('-- 3. Capability rows. Status is not set here; pass 5 raises it.');
  for (const capability of capabilities) {
    const contract = inception.screen_contracts.find((c) => c.capabilities.includes(capability.key));
    const authority = contract ? `${contract.authority.primary} → ${contract.authority.semester_role}` : `registry:${capability.domain}`;
    lines.push(
      `insert into private.registry_capabilities (capability_key, workspace_id, name, description, risk_tier, authority_model, status, requires_reconciliation)`,
      `  select ${literal(capability.key)}, w.id, ${literal(capability.name)}, ${literal(`${capability.domain} · ${capability.phase} · owner ${capability.owner}`)}, ${RISK_TIER[capability.risk]}, ${literal(authority)}, 'draft'::private.registry_status, ${contract?.authority.reconciliation_required ? 'true' : 'false'}`,
      `  from private.registry_workspaces w where w.workspace_key = ${literal(capability.workspace)}`,
      `  on conflict (capability_key) do update set workspace_id = excluded.workspace_id, name = excluded.name, description = excluded.description, risk_tier = excluded.risk_tier, authority_model = excluded.authority_model, requires_reconciliation = excluded.requires_reconciliation;`,
    );
  }
  lines.push('-- 4. Dependencies and evidence. A capability projected deployed needs its workspace deployed, which pass 2 guarantees.');
  for (const capability of capabilities) {
    const dependencies: Array<[string, string]> = [['workspace', capability.workspace], ...capability.systems.map((s): [string, string] => [s.startsWith('integrations.') ? 'integration' : 'system', s])];
    for (const [type, key] of dependencies) {
      lines.push(
        `insert into private.registry_capability_dependencies (capability_id, dependency_type, dependency_key, required_status)`,
        `  select c.id, ${literal(type)}, ${literal(key)}, 'deployed'::private.registry_status from private.registry_capabilities c where c.capability_key = ${literal(capability.key)}`,
        `  on conflict (capability_id, dependency_type, dependency_key) do update set required_status = excluded.required_status;`,
      );
    }
    for (const [stage, references] of Object.entries(capability.evidence)) for (const reference of references ?? []) {
      lines.push(
        `insert into private.registry_capability_evidence (capability_id, evidence_type, evidence_url, status)`,
        `  select c.id, ${literal(reference.kind)}, ${literal(`${reference.path}#${stage}`)}, 'draft'::private.registry_status from private.registry_capabilities c where c.capability_key = ${literal(capability.key)}`,
        `  on conflict (capability_id, evidence_type, evidence_url) do nothing;`,
      );
    }
  }
  lines.push('-- 5. Raise capabilities to their projected status.');
  for (const capability of capabilities) {
    const status = projectedStatus(capability.maturity);
    lines.push(`update private.registry_capabilities set status = ${statusLiteral(status)} where capability_key = ${literal(capability.key)} and status <> ${statusLiteral(status)};`);
  }
  lines.push('commit;', '');
  return lines.join('\n');
}
