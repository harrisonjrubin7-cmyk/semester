import type { RegistrySnapshot } from '../types.ts';
import { INCEPTION_OPERATING_SYSTEMS, JOURNEY_COUNT, type inceptionCoverage } from '../validators/inception-validator.ts';

type CoverageRow = ReturnType<typeof inceptionCoverage>[number];
interface EventRow { os: string; event: string; catalog_event: string | null; status: string }
interface EvidencePack { required: number; present: number; artifacts: Array<{ artifact: string; producer: string | null; status: string; present: boolean }> }

const cell = (value: string | readonly string[]): string => {
  const text = Array.isArray(value) ? (value.length ? value.join(', ') : '—') : String(value);
  return text.replace(/\\/g, "\\\\").replace(/\|/g, "\\|");
};
const yesNo = (ok: boolean, detail: string): string => `${ok ? 'yes' : 'no'} — ${detail}`;

/**
 * The coverage matrix the specification asks for, rendered from the registry
 * so it cannot disagree with it. Every figure here is counted, not typed.
 */
export function renderCoverageMarkdown(snapshot: RegistrySnapshot, coverage: CoverageRow[], events: EventRow[], pack: EvidencePack): string {
  const inception = snapshot.inception!;
  const capabilities = snapshot.capabilities;
  const productionReady = capabilities.filter((c) => c.maturity.production_ready).length;
  const carried = events.filter((e) => e.catalog_event !== null).length;
  const verifiedJourneys = inception.journeys.filter((j) => j.status === 'verified').length;
  const sandboxed = inception.adapters.filter((a) => a.sandbox_verified).length;
  const routes = inception.operating_systems.reduce((n, os) => n + os.routes.length, 0);
  const contractedRoutes = new Set(inception.screen_contracts.map((c) => c.route)).size;
  const deployedWorkspaces = (snapshot.workspaces ?? []).filter((w) => w.refs.deployments.length > 0).length;
  const workspaceCount = (snapshot.workspaces ?? []).length;

  const lines: string[] = [
    '# Inception coverage matrix',
    '',
    '<!-- Generated by packages/platform-control/scripts/build-atlas.ts from the registry. Edit the registry, then run `npm run registry:build` from the repository root. -->',
    '',
    `**Operating systems** ${inception.operating_systems.length} of ${INCEPTION_OPERATING_SYSTEMS.length} registered · **Routes** ${routes} · **Screen contracts** ${inception.screen_contracts.length} · **Required events** ${events.length} (${carried} carried by the event catalog, ${events.length - carried} proposed) · **Journeys** ${inception.journeys.length} of ${JOURNEY_COUNT} (${verifiedJourneys} verified) · **Adapters** ${inception.adapters.length} (${sandboxed} sandbox-verified) · **Evidence pack** ${pack.present} of ${pack.required} artifacts present`,
    '',
    '> **Claim ceiling.** A row here is scope and ownership. "designed" means the registry names the system; nothing in this file says a system operates, is deployed, or has been activated for a tenant. The deployment column is derived from the workspace registry\'s deployment evidence, which is empty.',
    '',
    '## Definition of inception completion',
    '',
    '| Claim | Holds |',
    '| --- | --- |',
    `| Every OS is deployed in production | ${yesNo(deployedWorkspaces === workspaceCount && workspaceCount > 0, `${deployedWorkspaces} of ${workspaceCount} pilot scopes carry deployment evidence`)} |`,
    `| Every route has a screen contract and all operational states | ${yesNo(contractedRoutes >= routes, `${contractedRoutes} of ${routes} routes have a contract`)} |`,
    `| Every capability has a passport, owner, runbook, contract and evidence | ${yesNo(productionReady === capabilities.length && capabilities.length > 0, `${productionReady} of ${capabilities.length} capabilities are production-ready`)} |`,
    `| Every required event is carried by the catalog | ${yesNo(carried === events.length, `${carried} of ${events.length}`)} |`,
    `| Every cross-OS journey passes end to end | ${yesNo(verifiedJourneys === inception.journeys.length, `${verifiedJourneys} of ${inception.journeys.length} verified`)} |`,
    `| Every integration has sandbox verification | ${yesNo(sandboxed === inception.adapters.length, `${sandboxed} of ${inception.adapters.length}`)} |`,
    `| Every production change produces the release evidence pack | ${yesNo(pack.present === pack.required, `${pack.present} of ${pack.required} artifacts present under release/`)} |`,
    '',
    '## Operating systems',
    '',
    '| Identifier | System | Workspace (pilot scopes) | Module (master domains) | User roles (from permissions) | Screens / contracts | Routes | Data (capabilities) | Permissions | Integrations | Journeys | Status | Evidence | Deployment | Blockers |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const row of coverage) {
    lines.push(`| ${row.identifier} | ${cell(row.system)} | ${cell(row.workspaces)} | ${cell(row.master_domains)} | ${cell(row.roles)} | ${cell([...row.screens_in_repo.map((s) => s.split('/').pop() ?? s), ...row.screen_contracts])} | ${cell(row.routes)} | ${cell(row.capabilities)} | ${cell(row.permissions)} | ${cell(row.adapters.map((a) => `${a.key.replace(/^adapter\./, '')} (${a.health})`))} | ${cell(row.journeys.map((j) => `${j.key.replace(/^journey\./, '#')} ${j.status}`))} | ${row.status} | ${cell(row.evidence)} | ${row.deployment} | ${cell(row.blockers)} |`);
  }
  lines.push('', '## Required events', '', '| OS | Required event | Catalog event | Status |', '| --- | --- | --- | --- |');
  for (const e of events) lines.push(`| ${e.os} | ${e.event} | ${e.catalog_event ?? '—'} | ${e.status} |`);
  lines.push('', '## Journeys', '', '| # | Journey | Crosses | Status | Tests | Gaps |', '| --- | --- | --- | --- | --- | --- |');
  for (const j of [...inception.journeys].sort((a, b) => a.number - b.number)) lines.push(`| ${j.number} | ${cell(j.name)} | ${cell(j.crosses)} | ${j.status} | ${cell(j.tests)} | ${cell(j.gaps)} |`);
  lines.push('', '## Adapters', '', '| Adapter | Used by | Required behavior | Declared health | Sandbox verified | Status |', '| --- | --- | --- | --- | --- | --- |');
  for (const a of [...inception.adapters].sort((x, y) => x.key.localeCompare(y.key))) lines.push(`| ${cell(a.adapter)} | ${cell(a.domains)} | ${cell(a.required_behavior)} | ${a.health} | ${a.sandbox_verified ? 'yes' : 'no'} | ${a.status} |`);
  lines.push('', '## Release evidence pack', '', '| Artifact | Producer | Present | Status |', '| --- | --- | --- | --- |');
  for (const a of pack.artifacts) lines.push(`| ${a.artifact} | ${cell(a.producer ?? '— (no producer yet)')} | ${a.present ? 'yes' : 'no'} | ${a.status} |`);
  lines.push('', '## Workstreams', '', '| Workstream | Deliverables | Registry groups | Status | Gaps |', '| --- | --- | --- | --- | --- |');
  for (const w of [...inception.workstreams].sort((x, y) => x.letter.localeCompare(y.letter))) lines.push(`| ${w.letter} · ${cell(w.name)} | ${cell(w.deliverables)} | ${cell(w.registry_groups)} | ${w.status} | ${cell(w.gaps)} |`);
  lines.push('');
  return lines.join('\n');
}
