/** The rows a gate owns. H owns every row. */
export const rowsOf = (gate: Gate): readonly string[] => (gate.id === 'H' ? REGISTER.map((r) => r.id) : gate.rows);

export interface GateVerdict {
  gate: Gate['id'];
  passes: boolean;
  byStatus: Partial<Record<Status, number>>;
  /** Rows short of launch approved, P0 first. */
  open: string[];
}

/**
 * A gate passes only when every row it owns is launch approved — and H also
 * needs every sign-off. There is no argument that forces it, for the reason
 * `launchreadiness.ts` gives: a checkbox is ticked by whoever holds the pen.
 */
export function verdict(gate: Gate, register: readonly Requirement[] = REGISTER, signoffs = SIGNOFFS): GateVerdict {
  const owned = new Set(rowsOf(gate));
  const rows = register.filter((r) => owned.has(r.id));
  const byStatus: Partial<Record<Status, number>> = {};
  for (const r of rows) byStatus[r.status] = (byStatus[r.status] ?? 0) + 1;
  const open = rows
    .filter((r) => r.status !== 'launch-approved')
    .sort((a, b) => a.severity.localeCompare(b.severity))
    .map((r) => r.id);
  const signed = gate.id !== 'H' || signoffs.every((s) => s.signed);
  return { gate: gate.id, passes: rows.length === owned.size && open.length === 0 && signed, byStatus, open };
}

