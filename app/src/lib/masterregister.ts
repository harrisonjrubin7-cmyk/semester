/**
 * The Master Launch Readiness Register: every requirement the day-one
 * enterprise launch plan sets, where the repository stands on each, and the
 * eight gates that decide whether Semester may launch as a whole platform.
 *
 * `docs/MASTER-LAUNCH-READINESS-REGISTER.md` is rendered from this file by
 * `masterregister.test.ts`; edit the data, then `npm run registers` from app/.
 *
 * ## How this relates to what is already here
 *
 * `launchreadiness.ts` is the go/no-go for a first pilot school: twelve gates,
 * twelve council seats. This is the wider register the day-one plan asks for — the
 * native LMS, interoperability, the whole AI, trust, reliability and commercial
 * surface — and it reuses that file's rule rather than inventing a softer one:
 * nothing is complete because it is designed, coded or documented, only when it
 * is evidenced and signed.
 *
 * ## What the statuses may claim
 *
 * The plan's nine states, and a test for each claim a state makes:
 *
 *   - `designed` cites a document; `building` and `implemented` cite code.
 *   - `tested` cites an automated test that runs on every change.
 *   - `evidenced`, `operational` and `launch-approved` need an artifact under
 *     `docs/evidence/` — a drill report, a UAT record, a signed review — and
 *     `launch-approved` needs every sign-off below. There is no such directory
 *     today, so no row can be above `tested`, and none is.
 *
 * `tested` is a claim about code, never about launch: a row can be `tested` and
 * still need a UAT, a drill, a certification or a contract, and its `gap` says
 * which. The row statuses were first assessed against `origin/main` at
 * `5bc0330` on 2026-09-28 and re-assessed the same day at `fd8fc0b`, after
 * #814, #819, #839, #893, #895, #896, #900, #901, #902 and #903 landed. Nine
 * rows rose to `tested` (IAM-004, STU-006, STU-008, STU-012, LMS-002, TRUST-005,
 * SRE-001, SUP-001, UOS-006), and sixteen more gained evidence or a narrower
 * gap without changing status; #908 then moved SRE-010 to `building` and its
 * call stands. PRG-002 then rose to `tested` with the claims register
 * (`ops/claims/`), which maps the public site's claims and no more. Nothing
 * fell.
 */

export const STATUSES = [
  'not-started',
  'designed',
  'building',
  'implemented',
  'tested',
  'evidenced',
  'operational',
  'launch-approved',
  'blocked',
] as const;

export type Status = (typeof STATUSES)[number];

export const STATUS_MEANING: Record<Status, string> = {
  'not-started': 'No implemented control/capability exists',
  designed: 'Requirements/architecture approved; not implemented',
  building: 'Implementation in progress',
  implemented: 'Deployed in non-production or production but not fully validated',
  tested: 'Functional/security/accessibility/reliability tests pass',
  evidenced: 'Current artifacts are collected and reviewed',
  operational: 'Monitored, supported, and used in production-like operation',
  'launch-approved': 'All required columns complete and accountable owners signed off',
  blocked: 'Cannot progress due to dependency, risk, staffing, or external decision',
};

/** The states that assert something happened outside the repository. */
export const NEEDS_EVIDENCE_DIR: readonly Status[] = ['evidenced', 'operational', 'launch-approved'];

export type Severity = 'P0' | 'P1' | 'P2';

export const DOMAINS = {
  PRG: 'Program and foundations',
  IAM: 'Identity, tenant, and authorization',
  STU: 'Student platform',
  LMS: 'Native LMS',
  INT: 'Interoperability and integrations',
  MIG: 'Migration',
  AI: 'AI and intelligence',
  UOS: 'Campus, career, and University OS modules',
  UX: 'UI and design system',
  A11Y: 'Accessibility',
  TRUST: 'Data trust',
  SEC: 'Security, privacy, and procurement',
  LEG: 'Legal',
  SRE: 'Reliability',
  SUP: 'Support',
  IMP: 'Implementation',
  COM: 'Commercial operations',
} as const;

export type Domain = keyof typeof DOMAINS;

export interface Evidence {
  /** Repository-relative. A test fails if it does not exist. */
  path: string;
  shows: string;
}

export interface Requirement {
  /** `<DOMAIN>-<nnn>`, stable. */
  id: string;
  capability: string;
  /** The exact observable condition needed at launch, as the plan words it. */
  requirement: string;
  /** The proof the plan asks for. */
  validation: string;
  severity: Severity;
  status: Status;
  evidence: Evidence[];
  /** What is missing before the row could be launch approved. Required unless approved. */
  gap: string;
}

export const domainOf = (id: string): Domain => id.split('-')[0] as Domain;

